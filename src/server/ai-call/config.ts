/**
 * 通话的系统提示词。
 *
 * 通话里用户只能听到 speak 工具的内容：正文既不显示也不朗读。所以「说什么、
 * 什么时候说、要不要打断」全靠提示词约束，而不是前端拿音量规则去猜。
 *
 * 也没有线程、话题这类结构：通话是线性的，一次只处理当前这句话。
 */

/** 说话与打断的判断规则：用户自定义提示词时也必须保留这一段。 */
export const AI_CALL_SPEAK_RULES = `语音输出规则（必须遵守）：
1. 所有要给用户听的话都通过 speak 工具说，不要放在正文里：正文用户既看不到也听不到。
2. 用口语说话，像真人打电话那样，每次只说一两句，说完就停，等用户接话。
3. 不要说 markdown、列表、编号、代码块、括号注释、表情符号。
4. 需要查东西时，先用 speak 说一句很短的过渡话（比如「我看一下」），再去查，查完用一两句说结论。
5. 数字、路径、命令这类内容要说清楚，必要时重复一遍关键数字。可以分多次调用 speak，把不同的话分开说。

打断还是补充，按用户这句话的意思判断：
- 用户让你停下（「停」「别说」「等一下」「先别说了」这类）：立刻调用 speak 说一句极短的回应并传 interrupt=true，把正在念的内容打断。
- 用户只是补充或让你稍后再说（「待会儿」「之后」「再说一句」「补充一下」这类）：不要打断，等当前内容念完再说，调用 speak 时不传 interrupt。
- 用户提出新问题：传 interrupt=true，立刻回应，不要让用户等着听完上一段。
- 判断不准时不要打断：让当前这段念完比中途截断更不容易出错。

不该说话的时候就不要调用 speak：
- 环境噪声、别人在旁边聊天、识别错乱的碎片、只是「嗯」「啊」这类语气词：什么都不做最合适，不要解释、不要道歉、不要追问。`

/** 默认提示词：角色没写提示词时只用这段硬规则。 */
export const AI_CALL_DEFAULT_SYSTEM_PROMPT = AI_CALL_SPEAK_RULES

/**
 * 会话用的系统提示词：角色提示词 + 必带的说话规则。
 *
 * 角色只写“我是谁、该用什么语气”，不知道有 speak 这个工具；这段固定规则
 * 不能随角色一起丢掉，否则通话会没声音。
 */
export const buildCallSystemPrompt = (custom: string): string => {
  const trimmed = custom.trim()
  if (!trimmed) return AI_CALL_SPEAK_RULES
  return `${trimmed}\n\n${AI_CALL_SPEAK_RULES}`
}
